NOVA.t = function (key) {
    var subs = Array.prototype.slice.call(arguments, 1).map(String);
    var text = '';
    try {
        if (NOVA.api && NOVA.api.i18n && NOVA.api.i18n.getMessage) {
            text = subs.length ? NOVA.api.i18n.getMessage(key, subs) : NOVA.api.i18n.getMessage(key);
        }
    } catch (e) {
        text = '';
    }
    if (!text) text = NOVA.FALLBACK[key] || key;
    if (subs.length) {
        for (var i = 0; i < subs.length; i++) {
            text = text.split('$' + (i + 1) + '$').join(subs[i]);
            text = text.split('$' + (i + 1)).join(subs[i]);
        }
        // A named placeholder the browser did not resolve (older engines are picky about the
        // case of the name) is filled positionally: one substitution per occurrence.
        var index = 0;
        text = text.replace(/\$[A-Za-z0-9_]+\$/g, function () {
            return subs[index] === undefined ? '' : subs[index++];
        });
    }
    return text;
};

/** Fills every [data-i18n] node in a page with the active language. */
NOVA.applyI18n = function (root) {
    var scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach(function (element) {
        element.textContent = NOVA.t(element.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach(function (element) {
        element.title = NOVA.t(element.getAttribute('data-i18n-title'));
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (element) {
        element.placeholder = NOVA.t(element.getAttribute('data-i18n-placeholder'));
    });
};

NOVA.uiLanguage = function () {
    try { return NOVA.api.i18n.getUILanguage(); } catch (e) { return 'en'; }
};
